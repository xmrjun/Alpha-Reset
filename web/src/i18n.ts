export const LANGS = ['zh', 'en'] as const;
export type Lang = (typeof LANGS)[number];
const STORAGE_KEY = 'alpha-lang';

/** 显式选择优先；否则按浏览器语言，只有中文环境才用中文，其余一律英文。 */
export function detectLang(): Lang {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved === 'zh' || saved === 'en') return saved;
  } catch { /* 隐私模式下存储不可用，仍可手动切换 */ }
  const prefs = typeof navigator === 'undefined' ? []
    : [...(navigator.languages ?? []), navigator.language].filter(Boolean);
  return prefs.some((tag) => String(tag).toLowerCase().startsWith('zh')) ? 'zh' : 'en';
}

export function persistLang(lang: Lang): void {
  try { localStorage.setItem(STORAGE_KEY, lang); } catch { /* 不依赖持久化 */ }
}

